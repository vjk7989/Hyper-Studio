import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { _electron as electron } from '../apps/workflow-ui/node_modules/@playwright/test/index.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const home = path.join(root, '.local-tmp', `workflow-control-smoke-${Date.now()}`)
const shared = path.join(root, '.local-tmp', 'packaged-electron-smoke-project-controls', 'shared-storage')
const executablePath = path.resolve(process.env.HYPER_STUDIO_SMOKE_EXE || path.join(root, '.local-tmp', 'installed-project-controls-final', 'Hyper-Studio.exe'))
if (!executablePath.startsWith(`${root}${path.sep}`) || !fs.existsSync(executablePath)) throw new Error('Smoke executable must be an existing repository-local file')
for (const folder of [home, path.join(home, 'appdata'), path.join(home, 'localappdata'), path.join(home, 'temp')]) fs.mkdirSync(folder, { recursive: true })
const env = { ...process.env, HOME: home, USERPROFILE: home, APPDATA: path.join(home, 'appdata'), LOCALAPPDATA: path.join(home, 'localappdata'), TEMP: path.join(home, 'temp'), TMP: path.join(home, 'temp'), TMPDIR: path.join(home, 'temp'), HYPER_STUDIO_USER_DATA: path.join(home, 'user-data'), ELECTRON_ENABLE_LOGGING: '1', ELECTRON_LOG_FILE: path.join(home, 'electron.log') }
const app = await electron.launch({ executablePath, cwd: root, env, args: ['--no-sandbox', '--disable-gpu', '--disable-dev-shm-usage'], timeout: 120000 })
const log = (...values) => process.stdout.write(`${values.map(value => typeof value === 'string' ? value : JSON.stringify(value)).join(' ')}\n`)
log('HOME', home)
try {
  const window = await app.firstWindow({ timeout: 45000 })
  const errors = []
  window.on('pageerror', error => errors.push(String(error)))
  window.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await window.waitForLoadState('domcontentloaded')
  await window.evaluate(folder => window.electronAPI.setSharedStorageRoot({ folder }), shared)
  await window.reload({ waitUntil: 'domcontentloaded' })
  await window.evaluate(() => { window.location.hash = '#/projects' })
  await window.getByTestId('new-project-card').waitFor({ state: 'visible', timeout: 30000 })
  const projectFolder = path.join(home, 'workflow-project')
  fs.mkdirSync(projectFolder, { recursive: true })
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }) }, projectFolder)
  await window.getByTestId('new-project-card').click()
  await window.getByPlaceholder('Project name').fill('Workflow controls')
  await window.getByText('Workflow mode', { exact: true }).click()
  await window.getByText('Choose a folder', { exact: true }).click()
  await window.getByPlaceholder('Project name').press('Enter')
  const iframe = window.locator('iframe[title="Hyper-Studio workflow canvas"]')
  await iframe.waitFor({ state: 'visible', timeout: 60000 })
  const canvas = window.frameLocator('iframe[title="Hyper-Studio workflow canvas"]')
  await canvas.locator('#graph-canvas').waitFor({ state: 'visible', timeout: 45000 })
  await window.waitForTimeout(1500)
  const engine = await window.evaluate(() => window.electronAPI.getWorkflowEngineStatus())
  const snapshot = async () => window.evaluate(async origin => {
    const target = document.querySelector('iframe[title="Hyper-Studio workflow canvas"]')?.contentWindow
    return await new Promise((resolve, reject) => {
      const requestId = crypto.randomUUID()
      const timeout = setTimeout(() => reject(new Error('snapshot timeout')), 12000)
      const onMessage = event => {
        if (event.source !== target || event.origin !== origin || event.data?.type !== 'hyper-studio:workflow-snapshot' || event.data.requestId !== requestId) return
        clearTimeout(timeout); window.removeEventListener('message', onMessage)
        event.data.error ? reject(new Error(event.data.error)) : resolve(event.data.workflow)
      }
      window.addEventListener('message', onMessage)
      target.postMessage({ type: 'hyper-studio:request-workflow', requestId }, origin)
    })
  }, new URL(engine.url).origin)
  log('ENGINE', engine)
  log('HOST BUTTONS', await window.locator('button').evaluateAll(els => els.filter(e => e.getBoundingClientRect().width).map(e => ({ text:e.textContent?.trim().slice(0,80), aria:e.getAttribute('aria-label'), title:e.getAttribute('title') })).slice(0,100)))
  log('CANVAS BUTTONS', await canvas.locator('button').evaluateAll(els => els.filter(e => e.getBoundingClientRect().width).map(e => ({ text:e.textContent?.trim().slice(0,80), aria:e.getAttribute('aria-label'), title:e.getAttribute('title'), testid:e.getAttribute('data-testid') })).slice(0,150)))
  log('CANVAS BODY', (await canvas.locator('body').innerText()).slice(0,4000))
  await window.screenshot({ path: path.join(home, 'initial.png') })
  await canvas.locator('#graph-canvas').press('Control+,')
  const settingsDialog = canvas.getByTestId('settings-dialog')
  await settingsDialog.waitFor({ state: 'visible', timeout: 10000 })
  log('INITIAL SETTINGS', (await settingsDialog.innerText()).slice(0,2500))
  log('INITIAL SETTINGS NAV', await settingsDialog.locator('[data-nav-id]').evaluateAll(els => els.map(e => ({ id:e.getAttribute('data-nav-id'), text:e.textContent?.trim() }))))
  await window.screenshot({ path: path.join(home, 'initial-settings.png') })
  await settingsDialog.locator('[data-nav-id="root/Appearance"]').click()
  log('APPEARANCE', (await settingsDialog.innerText()).slice(0,1800))
  log('APPEARANCE CONTROLS', await settingsDialog.locator('button, input, select').evaluateAll(els => els.filter(e => e.getBoundingClientRect().width).map(e => ({ tag:e.tagName, text:e.textContent?.trim().slice(0,70), aria:e.getAttribute('aria-label'), role:e.getAttribute('role'), type:e.getAttribute('type') })).slice(0,70)))
  await window.screenshot({ path: path.join(home, 'appearance.png') })
  await canvas.locator('body').press('Escape')
  await canvas.locator('#graph-canvas').press('Control+Shift+k')
  log('SHORTCUT VIA KEY', (await canvas.locator('body').innerText()).slice(-1500))
  await window.screenshot({ path: path.join(home, 'shortcuts-via-key.png') })
  await canvas.locator('body').press('Escape')
  await canvas.getByTestId('node-library-tab-button').click()
  log('LIBRARY BODY', (await canvas.locator('body').innerText()).slice(0,3500))
  log('LIBRARY INPUTS', await canvas.locator('input').evaluateAll(els => els.map(e => ({ placeholder:e.placeholder, aria:e.getAttribute('aria-label'), testid:e.getAttribute('data-testid') }))))
  await window.screenshot({ path: path.join(home, 'library.png') })
  await canvas.getByPlaceholder('Search...').fill('EmptyImage')
  await window.waitForTimeout(700)
  log('SEARCH BODY', (await canvas.locator('body').innerText()).slice(0,2500))
  log('SEARCH MATCHES', await canvas.getByText('EmptyImage', { exact: true }).count())
  await window.screenshot({ path: path.join(home, 'search-empty-image.png') })
  await canvas.getByText('Empty Image', { exact: true }).last().dblclick()
  await window.waitForTimeout(500)
  log('AFTER ADD SNAPSHOT', await snapshot())
  await window.screenshot({ path: path.join(home, 'added-empty-image.png') })
  await canvas.getByPlaceholder('Search...').fill('SaveImage')
  await window.waitForTimeout(500)
  log('SAVE SEARCH BODY', (await canvas.locator('body').innerText()).slice(0,1200))
  await canvas.getByText('Save Image', { exact: true }).last().dblclick()
  await window.waitForTimeout(500)
  log('AFTER ADD TWO', await snapshot())
  await window.screenshot({ path: path.join(home, 'two-nodes.png') })
  await window.getByRole('button', { name: 'Save', exact: true }).click()
  const saved = path.join(projectFolder, 'workflows', 'workflow.json')
  for (let i = 0; i < 40 && !fs.existsSync(saved); i++) await window.waitForTimeout(250)
  log('SAVE', fs.existsSync(saved), saved)
  const fixture = await snapshot()
  const empty = fixture.nodes.find(node => node.type === 'EmptyImage')
  const save = fixture.nodes.find(node => node.type === 'SaveImage')
  empty.pos = [100, 150]; empty.widgets_values = [64, 64, 1, 0]; empty.widgets_values_named = { width:64, height:64, batch_size:1, color:0 }
  save.pos = [500, 150]; save.widgets_values = ['workflow-control-ui']; save.widgets_values_named = { filename_prefix: 'workflow-control-ui' }
  empty.outputs[0].links = [1]; save.inputs[0].link = 1
  fixture.nodes = [empty, save]; fixture.links = [[1, empty.id, 0, save.id, 0, 'IMAGE']]; fixture.last_link_id = 1
  const source = path.join(home, 'linked-local.json')
  fs.writeFileSync(source, JSON.stringify(fixture))
  await app.evaluate(({ dialog }, sourcePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [sourcePath] }) }, source)
  await window.getByRole('button', { name: 'Import', exact: true }).click()
  const imported = path.join(projectFolder, 'workflows', 'linked-local.json')
  for (let i = 0; i < 40 && !fs.existsSync(imported); i++) await window.waitForTimeout(250)
  log('IMPORT', fs.existsSync(imported), fs.existsSync(imported) && fs.readFileSync(imported).equals(fs.readFileSync(source)))
  await window.waitForTimeout(1200)
  log('IMPORTED SNAPSHOT', await snapshot())
  await window.getByRole('button', { name: 'Open', exact: true }).click()
  const exported = path.join(home, 'linked-local-export.json')
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }) }, exported)
  await window.getByRole('button', { name: 'Export', exact: true }).click()
  for (let i = 0; i < 40 && !fs.existsSync(exported); i++) await window.waitForTimeout(250)
  log('EXPORT', fs.existsSync(exported), fs.existsSync(exported) && fs.readFileSync(exported).equals(fs.readFileSync(imported)))
  await window.screenshot({ path: path.join(home, 'imported-local-graph.png') })
  await canvas.getByTestId('queue-overlay-toggle').click()
  log('QUEUE OPEN', (await canvas.locator('body').innerText()).slice(-1200))
  await window.screenshot({ path: path.join(home, 'queue-open.png') })
  await canvas.getByTestId('queue-mode-menu-trigger').click()
  log('RUN OPTIONS', (await canvas.locator('body').innerText()).slice(-1200))
  await window.screenshot({ path: path.join(home, 'run-options.png') })
  await canvas.getByTestId('queue-mode-menu-trigger').click()
  await canvas.getByTestId('queue-button').click()
  log('RUN CLICKED', (await canvas.locator('body').innerText()).slice(-1200))
  for (let i = 0; i < 80 && !fs.existsSync(path.join(projectFolder, 'outputs', 'workflow-control-ui_00001_.png')); i++) await window.waitForTimeout(250)
  log('RUN OUTPUT', fs.existsSync(path.join(projectFolder, 'outputs', 'workflow-control-ui_00001_.png')))
  await window.screenshot({ path: path.join(home, 'run-complete.png') })
  log('CANCEL IDLE ENABLED', await canvas.getByRole('button', { name: 'Cancel current run' }).isEnabled())
  const toolbarShortcutClick = await canvas.getByRole('button', { name: 'Keyboard Shortcuts (Ctrl + Shift + k)' }).click({ timeout: 3000 }).then(() => 'clicked').catch(error => `blocked: ${String(error).slice(0, 300)}`)
  log('KEYBOARD TOOLBAR CLICK', toolbarShortcutClick)
  await window.screenshot({ path: path.join(home, 'keyboard-toolbar-click.png') })
  log('ERROR COUNT', errors.length)
} finally { await app.close() }
